/* Animal details dialog, home search/filter, gallery lightbox.
   Data comes from window.AB_DATA (assets/js/data.js, generated by src/build.py). */
(function () {
  "use strict";
  var data = window.AB_DATA;
  if (!data) return;

  var catById = {}, animalById = {};
  data.categories.forEach(function (c) { catById[c.id] = c; });
  data.animals.forEach(function (a) { animalById[a.id] = a; });

  function el(tag, attrs, children) {
    var n = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (k) {
      if (k === "text") n.textContent = attrs[k];
      else n.setAttribute(k, attrs[k]);
    });
    (children || []).forEach(function (c) { if (c) n.appendChild(c); });
    return n;
  }

  /* ---------- Animal details dialog ---------- */
  var dialog = document.getElementById("animal-dialog");
  var lastTrigger = null;

  function fillDialog(a) {
    var cat = catById[a.cat];
    dialog.style.setProperty("--c", cat.color);
    dialog.style.setProperty("--c-ink", cat.ink);
    dialog.style.setProperty("--c-tint", cat.tint);
    dialog.style.setProperty("--focus", a.focus || "50% 50%");

    var media = dialog.querySelector(".dialog__media");
    media.textContent = "";
    if (a.img) {
      media.appendChild(el("img", { src: "assets/img/animals/" + a.img + ".webp", alt: a.alt || a.name, width: "800", height: "800" }));
    } else {
      media.appendChild(el("div", { "class": "animal-card__emoji", "aria-hidden": "true", text: a.emoji || "" }));
    }

    dialog.querySelector("[data-d-cat]").textContent = cat.name;
    dialog.querySelector("#dialog-title").textContent = a.name;
    dialog.querySelector("[data-d-sci]").textContent = a.sci;
    dialog.querySelector("[data-d-summary]").textContent = a.summary;
    dialog.querySelector("[data-d-habitat]").textContent = a.habitat;
    dialog.querySelector("[data-d-diet]").textContent = a.diet;
    dialog.querySelector("[data-d-fun]").textContent = a.fun;
    var credit = dialog.querySelector("[data-d-credit]");
    credit.hidden = !a.credit;          // optional "credit" field in content.json
    credit.textContent = a.credit ? "Photo: " + a.credit : "";
    var link = dialog.querySelector("[data-d-wiki]");
    link.href = "https://en.wikipedia.org/wiki/" + a.wiki;
  }

  function openAnimal(id, trigger) {
    var a = animalById[id];
    if (!a || !dialog || typeof dialog.showModal !== "function") return;
    lastTrigger = trigger || null;
    fillDialog(a);
    dialog.showModal();
    dialog.querySelector(".dialog__close").focus();
  }

  if (dialog) {
    dialog.addEventListener("click", function (e) {
      // click on the backdrop (the dialog element itself) closes it
      if (e.target === dialog) dialog.close();
    });
    dialog.querySelector(".dialog__close").addEventListener("click", function () { dialog.close(); });
    dialog.addEventListener("close", function () {
      if (lastTrigger) lastTrigger.focus();
    });
  }

  document.addEventListener("click", function (e) {
    var btn = e.target.closest("[data-animal]");
    if (btn) openAnimal(btn.getAttribute("data-animal"), btn);
  });

  /* ---------- Gallery lightbox ---------- */
  var lightbox = document.getElementById("lightbox");
  if (lightbox) {
    var lbImg = lightbox.querySelector("img");
    var lbCap = lightbox.querySelector("figcaption");
    var lbTrigger = null;
    document.addEventListener("click", function (e) {
      var b = e.target.closest("[data-lightbox]");
      if (!b || typeof lightbox.showModal !== "function") return;
      lbTrigger = b;
      lbImg.src = b.getAttribute("data-lightbox");
      lbImg.alt = b.getAttribute("data-alt") || "";
      lbCap.textContent = b.getAttribute("data-caption") || "";
      lightbox.showModal();
      lightbox.querySelector(".dialog__close").focus();
    });
    lightbox.addEventListener("click", function (e) { if (e.target === lightbox) lightbox.close(); });
    lightbox.querySelector(".dialog__close").addEventListener("click", function () { lightbox.close(); });
    lightbox.addEventListener("close", function () { if (lbTrigger) lbTrigger.focus(); });
  }

  /* ---------- Search and filter (home page) ---------- */
  var grid = document.getElementById("explore-grid");
  if (grid) {
    var input = document.getElementById("animal-search");
    var chips = Array.prototype.slice.call(document.querySelectorAll("[data-filter]"));
    var count = document.getElementById("result-count");
    var empty = document.getElementById("empty-state");
    var items = Array.prototype.slice.call(grid.children);
    var activeCat = "all";

    // Build a lowercase search string for each card once
    var haystack = items.map(function (li) {
      var a = animalById[li.getAttribute("data-id")];
      var cat = catById[a.cat];
      return [a.name, a.sci, a.summary, a.habitat, a.diet, cat.name].join(" ").toLowerCase();
    });

    function apply() {
      var terms = input.value.toLowerCase().split(/\s+/).filter(Boolean);
      var shown = 0;
      items.forEach(function (li, i) {
        var okCat = activeCat === "all" || li.getAttribute("data-cat") === activeCat;
        var okText = terms.every(function (t) { return haystack[i].indexOf(t) !== -1; });
        var visible = okCat && okText;
        li.hidden = !visible;
        if (visible) shown++;
      });
      count.textContent = shown === 1 ? "1 animal found" : shown + " animals found";
      empty.hidden = shown !== 0;
    }

    input.addEventListener("input", apply);
    chips.forEach(function (chip) {
      chip.addEventListener("click", function () {
        activeCat = chip.getAttribute("data-filter");
        chips.forEach(function (c) { c.setAttribute("aria-pressed", String(c === chip)); });
        apply();
      });
    });
    var reset = document.getElementById("reset-filters");
    if (reset) reset.addEventListener("click", function () {
      input.value = "";
      chips[0].click();
      input.focus();
    });
    apply();
  }
})();
